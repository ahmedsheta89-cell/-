    fun diagnoseWordMakharij(uthmaniWord: String): MakharijPhoneticDiagnosis {
        val norm = ArabicTextNormalizer.normalizeForSearch(uthmaniWord)
        return when {
            norm.contains("ض") -> makharijDictionary.first { it.letterAr == "ض" }
            norm.contains("ص") -> makharijDictionary.first { it.letterAr == "ص" }
            norm.contains("ق") -> makharijDictionary.first { it.letterAr == "ق" }
            norm.contains("ع") -> makharijDictionary.first { it.letterAr == "ع" }
            norm.contains("د") -> makharijDictionary.first { it.letterAr == "د" }
            else -> makharijDictionary.first { it.letterAr == "ر" }
        }
    }

